package com.nextify.mab.render;

import com.nextify.mab.AnalysisResult;
import com.nextify.mab.model.BoundStatement;
import com.nextify.mab.model.Diagnostic;
import com.nextify.mab.model.MapperInterface;
import com.nextify.mab.model.MapperUnit;
import com.nextify.mab.model.MapperXml;
import com.nextify.mab.model.ResultMapInfo;

import java.util.List;

/** Renders an {@link AnalysisResult} as a compact Markdown document meant to be read by an LLM. */
public final class MarkdownRenderer {

    private final boolean includeResultMaps;

    public MarkdownRenderer(boolean includeResultMaps) {
        this.includeResultMaps = includeResultMaps;
    }

    public String render(AnalysisResult result) {
        StringBuilder sb = new StringBuilder();
        List<Diagnostic> diagnostics = result.getDiagnostics();

        sb.append("# MyBatis Context\n\n");
        sb.append("> Generated by [mybatis-ai-bridge](https://github.com/Libertyzzzz/mybatis-ai-bridge). ")
                .append("Each mapper method is listed with the SQL bound to it (XML or annotation).\n")
                .append("> Dynamic SQL tags are kept, `<include>` fragments are inlined, comments and whitespace are stripped.\n\n");
        sb.append("**").append(result.getUnits().size()).append(" mappers · ")
                .append(result.getStatementCount()).append(" statements");
        if (!diagnostics.isEmpty()) {
            sb.append(" · ").append(diagnostics.size()).append(" diagnostics (see end)");
        }
        sb.append("**\n\n");

        for (MapperUnit unit : result.getUnits()) {
            renderUnit(unit, sb);
        }

        if (!diagnostics.isEmpty()) {
            sb.append("## Diagnostics\n\n");
            for (Diagnostic d : diagnostics) {
                sb.append("- **").append(d.getLevel()).append("** `").append(d.getLocation())
                        .append("` — ").append(d.getMessage()).append('\n');
            }
            sb.append('\n');
        }
        return sb.toString();
    }

    private void renderUnit(MapperUnit unit, StringBuilder sb) {
        sb.append("## ").append(unit.getSimpleName()).append("\n\n");
        sb.append("- namespace: `").append(unit.getNamespace()).append("`\n");
        MapperInterface mi = unit.getMapperInterface();
        if (mi != null) {
            sb.append("- interface: `").append(mi.getRelativePath()).append("`\n");
            if (!mi.getExtendsTypes().isEmpty()) {
                sb.append("- extends: ");
                for (int i = 0; i < mi.getExtendsTypes().size(); i++) {
                    sb.append(i == 0 ? "" : ", ").append('`').append(mi.getExtendsTypes().get(i)).append('`');
                }
                if (mi.isInheritsGenericCrud()) {
                    sb.append(" — inherited generic CRUD methods are not listed");
                }
                sb.append('\n');
            }
        }
        for (MapperXml x : unit.getXmls()) {
            sb.append("- xml: `").append(x.getRelativePath()).append("`\n");
        }
        if (includeResultMaps) {
            for (MapperXml x : unit.getXmls()) {
                for (ResultMapInfo rm : x.getResultMaps()) {
                    sb.append("- resultMap `").append(rm.getId()).append("` → `").append(rm.getType()).append('`');
                    if (rm.getExtendsId() != null) {
                        sb.append(" (extends `").append(rm.getExtendsId()).append("`)");
                    }
                    if (!rm.getMappings().isEmpty()) {
                        sb.append(": ").append(String.join(", ", rm.getMappings()));
                    }
                    sb.append('\n');
                }
            }
        }
        sb.append('\n');

        for (BoundStatement e : unit.getEntries()) {
            renderEntry(e, sb);
        }
    }

    private static void renderEntry(BoundStatement e, StringBuilder sb) {
        sb.append("### `").append(e.getSignature() != null ? e.getSignature() : e.getName()).append("`\n\n");
        if (e.getDoc() != null) {
            sb.append("> ").append(e.getDoc()).append("\n\n");
        }
        StringBuilder meta = new StringBuilder();
        if (e.getKind() != null) {
            meta.append('`').append(e.getKind()).append('`');
        }
        if (e.getAttributes() != null) {
            meta.append(" · ").append(e.getAttributes());
        }
        switch (e.getSource()) {
            case XML:
                meta.append(" · xml");
                break;
            case ANNOTATION:
                meta.append(" · annotation");
                break;
            case PROVIDER:
                meta.append(" · SQL built at runtime by provider");
                break;
            case DEFAULT_METHOD:
                meta.append("Java default method (no SQL)");
                break;
            case UNBOUND:
                meta.append("⚠ no SQL binding found");
                break;
            case ORPHAN:
                meta.append(" · xml only — no matching interface method");
                break;
            default:
                break;
        }
        sb.append(meta).append("\n\n");
        if (e.getSql() != null && !e.getSql().isEmpty()) {
            sb.append(e.getSource() == BoundStatement.Source.PROVIDER ? "```java\n" : "```sql\n")
                    .append(e.getSql()).append("\n```\n\n");
        }
    }
}
